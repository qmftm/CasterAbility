package me.qmftm.casterability.game

/**
 * 이미 걸려 있는 상태이상에 같은 것을 또 걸었을 때 어떻게 할지.
 *
 * 능력마다 직접 정하지 않고 여기서 한 번에 정해두면,
 * 여러 능력이 같은 상태이상을 걸어도 규칙이 어긋나지 않는다.
 */
enum class StatusEffectMode {
    /** 더 긴 쪽만 남긴다. 짧게 다시 걸어도 남은 시간이 줄지 않는다. (기본) */
    LONGEST,

    /** 남은 시간에 더한다. 여러 번 걸수록 길어진다. */
    STACK,

    /** 남은 시간과 상관없이 새 값으로 덮어쓴다. 짧게 걸면 줄어든다. */
    REPLACE,

    /** 이미 걸려 있으면 아무것도 하지 않는다. */
    IGNORE,
}
